// if...else selects between two blocks.
// if runs when the condition is true.
// else runs when the condition is false.

/*
Syntax:

if (condition) {
    // Runs when the condition is true
} else {
    // Runs when the condition is false
}
*/

let hasBankAccountAccess = false;

if (hasBankAccountAccess) {
    console.log("You have access to your bank account");
} else {
    console.log("You do not have access to your bank account");
}

console.log("Bank account access check completed");

// Output:
// You do not have access to your bank account
// Bank account access check completed

