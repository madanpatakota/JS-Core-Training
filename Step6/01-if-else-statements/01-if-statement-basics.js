// if runs its code block when the condition is true.

/*
Syntax:

if (condition) {
    // Code to execute when the condition is true
}
*/

console.log("Before checking the conditions");

if (true) {
    console.log("The true condition block executed");
}

if (false) {
    console.log("This message will not appear");
}

console.log("After checking the conditions");

// Output:
// Before checking the conditions
// The true condition block executed
// After checking the conditions